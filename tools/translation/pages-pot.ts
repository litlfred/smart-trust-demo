#!/usr/bin/env bun
/**
 * `.pot` templates for this instance's published pages, one per (locale, page).
 *
 * The harness's `translation:pot` serves `translation:drift`'s findings (pages
 * already published in a locale with no catalogue), so it names nothing here,
 * where no page has been translated yet. This is the same extraction over the
 * pages this instance publishes: `extractMarkdown` + `formatPot` +
 * `potWithoutTimestamp` from `cat-harness-tools/pipeline/pot-extract.ts`,
 * nothing added to them.
 *
 * Which pages, and why:
 * - every `docs/**.md` page: the authored source of the site and of the IG
 *   pages `tools/ig-gen/ig_gen.py` copies from it (DOC_PAGES). Its template is
 *   `translations/<locale>/<path under docs/>.pot`, the harness's convention,
 *   so `po-inject` and `translation:drift` find it.
 * - every `input/pagecontent/*.md` page that is NOT a copy of a docs page: the
 *   hand-written IG pages and the ones ig_gen writes from JSON (personas,
 *   dictionary, scenarios, …). Template `translations/<locale>/pagecontent/<page>.pot`.
 *   A copy of a docs page is skipped: its strings are the docs page's.
 *
 * FHIR resources are not extracted: they use FHIR's own designation /
 * translation mechanism. The BPMN templates are `translate-bpmn`'s.
 *
 * Usage:
 *   bun tools/translation/pages-pot.ts           # write every template
 *   bun tools/translation/pages-pot.ts --check   # exit 1 if one is missing or stale
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";

import { extractMarkdown, formatPot, potWithoutTimestamp } from "../../cat-harness-tools/pipeline/pot-extract.ts";

const ROOT = resolve(import.meta.dir, "..", "..");
/** Target locales: the six UN languages less the source, `en`. */
const LOCALES = ["ar", "es", "fr", "ru", "zh"];
const GENERATED_FROM_DOCS = /^<!-- Generated by tools\/ig-gen\/ig_gen\.py from docs\//;

function walk(dir: string): string[] {
  return readdirSync(dir, { withFileTypes: true }).flatMap((e) =>
    e.isDirectory() ? walk(join(dir, e.name)) : e.name.endsWith(".md") ? [join(dir, e.name)] : [],
  );
}

/** [source path relative to ROOT, template path relative to translations/<locale>/]. */
export function pages(): [string, string][] {
  const out: [string, string][] = [];
  for (const f of walk(join(ROOT, "docs")).sort()) {
    out.push([relative(ROOT, f), relative(join(ROOT, "docs"), f).replace(/\.md$/, ".pot")]);
  }
  const pc = join(ROOT, "input", "pagecontent");
  for (const f of readdirSync(pc).filter((n) => n.endsWith(".md")).sort()) {
    if (GENERATED_FROM_DOCS.test(readFileSync(join(pc, f), "utf8"))) continue;
    out.push([`input/pagecontent/${f}`, `pagecontent/${f.replace(/\.md$/, ".pot")}`]);
  }
  return out;
}

const check = process.argv.includes("--check");
let bad = 0;
let msgids = 0;
const list = pages();
for (const [src, tpl] of list) {
  const entries = extractMarkdown(readFileSync(join(ROOT, src), "utf8"), src);
  if (!entries.length) continue;
  msgids += entries.length;
  for (const locale of LOCALES) {
    const pot = formatPot(entries, { projectName: "smart-trust-demo", locale });
    const path = join(ROOT, "translations", locale, tpl);
    const current = existsSync(path) && potWithoutTimestamp(readFileSync(path, "utf8")) === potWithoutTimestamp(pot);
    if (current) continue;
    if (check) {
      console.error(`  ✗ ${relative(ROOT, path)} ${existsSync(path) ? "stale" : "missing"}`);
      bad++;
    } else {
      mkdirSync(dirname(path), { recursive: true });
      writeFileSync(path, pot);
    }
  }
}
if (check && bad) {
  console.error(`${bad} page template(s) missing or stale: bun tools/translation/pages-pot.ts`);
  process.exit(1);
}
console.log(`✓ ${list.length} page(s), ${msgids} msgid(s), templates ${check ? "current" : "written"} for ${LOCALES.join(", ")}.`);
