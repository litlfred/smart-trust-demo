def slug(s):
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")


def instance_term(country, ra_block):
    """The glossary id of a country's instance of an RA building block (tools/archimate/overlay.py names it the same)."""
    return f"instance-{slug(country)}-{slug(ra_block)}"


