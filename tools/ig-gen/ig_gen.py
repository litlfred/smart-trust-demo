# A persona's avatar, drawn as the harness's journeys viewer draws it
# (cat-harness-tools scripts/journeys/render.ts, personaOf): the picture
# meta.persona.avatar names (a path from the repository root) when there is
# one, else meta.persona.icon, else meta.persona.initials or the initials of
# the persona's name, on meta.persona.color. It is one small SVG carried as a
# data URI, so it shows on the IG Publisher's page and the AST site's alike
# (neither route copies an image a description names relatively).
AVATAR_SIZE = 40
AVATAR_COLOR = "#64748b"  # when the persona names no colour
AVATAR_MIME = {".svg": "image/svg+xml", ".png": "image/png", ".jpg": "image/jpeg", ".jpeg": "image/jpeg",
               ".webp": "image/webp", ".gif": "image/gif"}


def _xml(s):
    return (s or "").replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace('"', "&quot;")


def avatar_svg(a):
    """The SVG of an actor's avatar, or None when it has no persona."""
    p = a.get("meta", {}).get("persona")
    if not p:
        return None
    n, r = AVATAR_SIZE, AVATAR_SIZE // 2
    name = p.get("name") or a["title"]
    color = p.get("color") or AVATAR_COLOR
    head = (f'<svg xmlns="http://www.w3.org/2000/svg" width="{n}" height="{n}" viewBox="0 0 {n} {n}" '
            f'role="img" aria-label="{_xml(name)}"><title>{_xml(name)}</title>')
    src = p.get("avatar")
    if src:
        f = (ROOT / src).resolve()
        if ROOT not in f.parents or not f.is_file() or f.suffix.lower() not in AVATAR_MIME:
            sys.exit(f"ig-gen: scenarios/actors/{a['id']}.json: meta.persona.avatar {src} is not an image in the repository")
        data = base64.b64encode(f.read_bytes()).decode("ascii")
        return (head + f'<defs><clipPath id="c"><circle cx="{r}" cy="{r}" r="{r}"/></clipPath></defs>'
                f'<circle cx="{r}" cy="{r}" r="{r}" fill="{_xml(color)}"/>'
                f'<image href="data:{AVATAR_MIME[f.suffix.lower()]};base64,{data}" width="{n}" height="{n}" '
                f'preserveAspectRatio="xMidYMid slice" clip-path="url(#c)"/></svg>')
    label = p.get("icon") or p.get("initials") or "".join(
        w[0].upper() for w in name.split() if re.match(r"[A-Za-z]", w))[:2] or a["id"][:2].upper()
    return (head + f'<circle cx="{r}" cy="{r}" r="{r}" fill="{_xml(color)}"/>'
            f'<text x="{r}" y="{r}" dy="0.35em" text-anchor="middle" font-family="sans-serif" font-size="{n * 2 // 5}" '
            f'font-weight="600" fill="#ffffff">{_xml(label)}</text></svg>')


def avatar_md(a):
    svg = avatar_svg(a)
    if svg is None:
        return ""
    name = a["meta"]["persona"].get("name") or a["title"]
    return f"![{name}](data:image/svg+xml;base64,{base64.b64encode(svg.encode()).decode('ascii')}) "


def persona_heading(p):
    """The heading of a person on the personas page (gen_personas)."""
    return f"{p['name']} ({p['role']}, {p['country']})"


def scenario_heading(sc):
    """The heading of a user scenario on the scenarios page (gen_user_scenarios)."""
    return f"{sc['title']} ({sc['where']}, {sc['when']})"


def _task_kinds(bpmn_file):
    """{flow node id: its BPMN element name (userTask, exclusiveGateway, ...)} of one process file."""
    proc = next(ET.parse(bpmn_file).getroot().iter(BPMN + "process"))
    return {n.get("id"): n.tag.rsplit("}", 1)[1] for n in proc.iter() if n.get("id")}


def implicated(role, by_role, ctx):
    """Markdown: what one role is implicated in, each item a link to its page and anchor in this guide.

    Read from the graph, never listed: the user-scenario steps it takes part
    in (a step whose tasks lie in the role's lanes, or whose people play the
    role, unless the step's processes give that person's part to another of
    their roles), the user stories told in its voice, the lanes and tasks it
    performs, the decisions in those lanes (the DMN decision tables that serve
    its tasks, the BPMN gateways in its lanes), the data sets its tasks record
    or read, and the indicators that count those decisions.
    """
    rid = role["id"]
    people = by_role.get(rid, [])
    lanes = {}  # process file name -> (process, [lane nodes])
    for p in ctx["procs"]:
        for l in p["lanes"]:
            if l["role"] == rid:
                lanes.setdefault(p["file"].name, (p, []))[1].extend(l["nodes"])
    mine = {(f, n) for f, (_, nodes) in lanes.items() for n in nodes}
    out = []

    # User scenarios: one item per journey, naming its steps.
    items = []
    for sc in ctx["scenarios"]:
        steps = []
        for st in sc["steps"]:
            procs = [r["process"].rsplit("/", 1)[-1] for r in st.get("realisedBy", [])]
            in_lanes = {l["role"] for p in ctx["procs"] if p["file"].name in procs for l in p["lanes"]}
            tasks = any((f, t) in mine for r in st.get("realisedBy", [])
                        for f in [r["process"].rsplit("/", 1)[-1]] for t in r["tasks"])
            who = [st.get("lead")] + [e["actor"] for e in st.get("experiences", [])]
            here = [a["id"] for a in people if a["id"] in who and (rid in in_lanes or not set(ctx["roles_of"][a["id"]]) & in_lanes)]
            if tasks or here:
                lead = [ctx["names"][a] for a in here if a == st.get("lead")]
                steps.append(f"{st['id']} {st['title']}" + (f" (told through {lead[0]})" if lead else ""))
        if steps:
            items.append(f"- [{sc['title']}](scenarios.html#{anchor(scenario_heading(sc))}): " + "; ".join(steps))
    if items:
        out += ["**In the user scenarios**:", ""] + items + [""]

    stories = [s for s in ctx["stories"] if s["role"]["role"] == rid]
    if stories:
        out += [f"**User stories** ([all stories](scenarios.html#user-stories)):", ""]
        out += [f"- I want to {s['want'][:1].lower() + s['want'][1:]}" + (f", so that {s['soThat']}" if s.get("soThat") else "")
                for s in stories] + [""]

    items = []
    for f, (p, nodes) in lanes.items():
        kinds = ctx["kinds"][f]
        tasks = [p["names"].get(n, n) for n in nodes if kinds.get(n, "").endswith("Task") or kinds.get(n) in ("task", "callActivity")]
        items.append(f"- [{p['name']}](business-processes.html#{anchor(p['name'])}): "
                     + ("; ".join(tasks) if tasks else "its lane holds no task"))
    if items:
        out += ["**Lanes and tasks in the business processes**:", ""] + items + [""]

    items, tables = [], []
    for d in ctx["decisions"]:
        served = [ctx["procnames"][f].get(t, t) for f, t in d["serves"] if (f, t) in mine]
        if served:
            tables.append(d["code"])
            title = f"{d['code']} {d['name']}"
            items.append(f"- Decision table [{title}](decision-logic.html#{anchor(title)}), in: " + "; ".join(served))
    for f, (p, nodes) in lanes.items():
        for n in nodes:
            if ctx["kinds"][f].get(n, "").endswith("Gateway"):
                items.append(f"- Gateway \"{p['names'].get(n, n)}\" in [{p['name']}](business-processes.html#{anchor(p['name'])})")
    if items:
        out += ["**Decisions it makes**:", ""] + items + [""]

    items = []
    for m in ctx["dictionary"]["models"]:
        if any((s["process"], t) in mine for s in m["serves"] for t in s["tasks"]):
            title = _model_heading(m)
            items.append(f"[{title}](dictionary.html#{anchor(title)})")
    if items:
        out += ["**Data sets its tasks record or read**: " + "; ".join(items), ""]

    items = []
    for ind in ctx["indicators"]:
        if set(ind["decisionTables"]) & set(tables):
            title = f"{ind['code']} {ind['title']}"
            items.append(f"[{title}](indicators.html#{anchor(title)})")
    if items:
        out += ["**Indicators that count its decisions**: " + "; ".join(items), ""]
    return "\n".join(out).rstrip()


def actor_context(roles, by_role):
    """What implicated() reads, read once."""
    procs = graph.processes(ROOT)
    roles_of = {a["id"]: a.get("roles", []) for a in actors()}
    names = {a["id"]: (a.get("meta", {}).get("persona") or {}).get("name") or a["title"] for a in actors()}
    return {
        "procs": procs,
        "kinds": {p["file"].name: _task_kinds(p["file"]) for p in procs},
        "procnames": {p["file"].name: p["names"] for p in procs},
        "scenarios": user_scenarios(),
        "stories": load("scenarios/stories.json")["stories"],
        "decisions": dak.decisions(ROOT),
        "dictionary": dak.dictionary(ROOT),
        "indicators": dak.indicators(ROOT),
        "roles_of": roles_of,
        "names": names,
    }


def played_by_md(a):
    """One person or system that plays a role: its avatar, and its name linked to its entry on the personas page."""
    p = a.get("meta", {}).get("persona")
    if p:
        return f"- {avatar_md(a)}[{p['name']}](personas.html#{anchor(persona_heading(p))}), {a['title']}"
    return f"- {a['title']}"


def gen_actor_fsh(roles, by_role):
    files = {}
    ctx = actor_context(roles, by_role)
    for r in roles:
        derived = []
        for a in by_role.get(r["id"], []):
            for url in a.get("meta", {}).get("definedBy", []):
                if url not in derived:
                    derived.append(url)
        desc = r["description"]
        if r.get("persona"):
            desc += "\n\n**Persona**: " + r["persona"]
        if r.get("otherNames"):
            desc += "\n\n**Also known as**: " + "; ".join(r["otherNames"])
        played = by_role.get(r["id"], [])
        if played:
            desc += "\n\n**Played in the journeys by** (fictional):\n\n" + "\n".join(played_by_md(a) for a in played)
        more = implicated(r, by_role, ctx)
        if more:
            desc += "\n\n" + more
        lines = [
            FSH_HEADER.format(src="scenarios/roles.json"),
            f"Instance: {actor_instance(r)}",
            "InstanceOf: ActorDefinition",
            "Usage: #definition",
            f'* name = "{pascal(r["id"])}"',
            f'* title = "{fsh_str(r["title"])}"',
            "* status = #draft",
            "* experimental = true",
            f"* type = #{KIND_TYPE[r['actorKinds'][0]]}",
            f'* description = """\n{desc}\n"""',
            f'* documentation = "{REPO}scenarios/roles.json"',
        ]
        for url in derived:
            lines.append(f'* derivedFrom[+] = "{url}"')
        files[f"input/fsh/actors/{actor_instance(r)}.fsh"] = "\n".join(lines) + "\n"
    return files


def gen_personas(roles, by_role):
    out = [HEADER.format(src="scenarios/roles.json and scenarios/actors/*.json")]
    out.append("These are the generic personas of the journeys J1 to J4: the roles that play the lanes of the "
               "[business processes](business-processes.html), each defined as an `ActorDefinition`. "
               "The people and systems that play them in the journeys are fictional.\n")
    for kind, heading in (("person", "Generic personas"), ("system", "System actors"), ("external", "External actors")):
        rows = [r for r in roles if r["actorKinds"][0] == kind]
        if not rows:
            continue
        out.append(f"\n### {heading}\n")
        out.append("| Role | Description | Played by (fictional) | Also known as |\n|---|---|---|---|")
        for r in rows:
            link = f"[{cell(r['title'])}](ActorDefinition-{actor_instance(r)}.html)"
            played = "; ".join(a["title"] for a in by_role.get(r["id"], []))
            out.append(f"| {link} | {cell(r['description'])} | {cell(played)} | {cell('; '.join(r.get('otherNames', [])))} |")
        out.append("{: .grid }")
    people = [a for a in actors() if a.get("meta", {}).get("persona")]
    if people:
        out.append("\n### The people of the journeys\n")
        out.append("Each is fictional. Their goals, needs and frustrations are kept in "
                   "`scenarios/actors/*.json` (`meta.persona`), and the VaxLink walkthrough shows the same text.\n")
        for a in people:
            p = a["meta"]["persona"]
            out.append(f"\n#### {persona_heading(p)}\n")
            out.append(f"{a['description']}\n")
            out.append(f"- **Goal:** {p['goal']}")
            out.append(f"- **Needs:** {'; '.join(p['needs'])}")
            out.append(f"- **Frustrations:** {'; '.join(p['frustrations'])}")
    others = [a for a in actors() if not a.get("roles") and not a.get("meta", {}).get("persona")]
    if others:
        out.append("\n### Other people in the journeys\n")
        for a in others:
            out.append(f"- **{a['title']}**: {a['description']}")
    return "\n".join(out) + "\n"


# The IGs whose actor definitions the journeys' actors derive from, by canonical base.
IG_LABEL = {
    "smart.who.int/trust": "WHO SMART Trust",
    "smart.who.int/trust-phw": "WHO SMART Trust PHW",
    "profiles.ihe.net/ITI/VHL": "IHE VHL",
}


def canonical_link(url):
    """A FHIR canonical as a link to its page in the IG that publishes it.

    A canonical (http://smart.who.int/trust/ActorDefinition/Issuer) names a
    resource; it is not a page. The IG Publisher writes the resource's page
    at <base>/<Type>-<id>.html, served over https
    (https://smart.who.int/trust/ActorDefinition-Issuer.html). The text names
    the IG and the id.
    """
    m = re.match(r"https?://(.+)/([A-Z][A-Za-z]+)/([A-Za-z0-9.\-]+)$", url)
    if not m:
        return f"<{url}>"
    base, rtype, rid = m.groups()
    return f"[{IG_LABEL.get(base, base)} {rid}](https://{base}/{rtype}-{rid}.html)"


def gen_system_actors(roles, by_role):
    out = [HEADER.format(src="scenarios/roles.json and scenarios/actors/*.json")]
    out.append("The system and external actors of the journeys, and the actor definitions of WHO SMART Trust, "
               "WHO smart-trust-phw and IHE ITI VHL each is derived from.\n")
    out.append("| Actor | Derived from |\n|---|---|")
    for r in roles:
        if r["actorKinds"][0] == "person":
            continue
        urls = []
        for a in by_role.get(r["id"], []):
            urls += [u for u in a.get("meta", {}).get("definedBy", []) if u not in urls]
        link = f"[{cell(r['title'])}](ActorDefinition-{actor_instance(r)}.html)"
        out.append(f"| {link} | {'<br/>'.join(canonical_link(u) for u in urls)} |")
    out.append("{: .grid }")
    return "\n".join(out) + "\n"


def gen_processes(procs, roles):
    titles = {r["id"]: r["title"] for r in roles}
    out = [HEADER.format(src="processes/content/*.bpmn")]
    out.append("One business process per journey. Each lane is a role on the [personas](personas.html) page; "
               "each task names the skill that performs it. The BPMN source of each process is in "
               "`processes/content/`, copied into the guide as `input/business-processes/`. "
               "Select a step's title to open it, or open a process in the [process viewer](cat-harness/processes/), "
               "which lists each task and the skill that performs it.\n")
    # The harness's task panel: the same client and styles the process pages use.
    out.append(f'<link rel="stylesheet" href="{PROCESS_VIEWER}task-panel.css" />\n'
               f'<script src="{PROCESS_VIEWER}task-panel.js" defer></script>\n')
    out.append("| Process | Lanes | BPMN |\n|---|---|---|")
    for p in procs:
        lanes = ", ".join(titles[l] for l in p["lanes"])  # an unknown role is an error (repo_checks names it)
        out.append(f"| [{cell(p['name'])}](#{anchor(p['name'])}) | {cell(lanes)} | [{p['file'].name}]({REPO}processes/content/{p['file'].name}) |")
    out.append("{: .grid }")
    for p in procs:
        stem = p["file"].stem
        viewer = f"cat-harness/processes/{stem}.html"
        out.append(f"\n### {p['name']}\n")
        # The drawing as the process pages show it, through the same harness
        # parts: render:bpmn's drawing (assets/img/workflows/, written at
        # publish, each step's title linked), inlined and framed by the site's
        # docs-ui.js, and the task panel's ⓘ markers from the process's panel
        # data. Whether that panel shows skills is the site's declaration
        # (index.config.json site.taskSkills), not this page's.
        out.append(f'<figure class="bpmn-figure pt-diagram" data-panel="{PROCESS_VIEWER}{stem}.tasks.json">'
                   f'<img src="{WORKFLOWS}{stem}.svg" alt="BPMN diagram: {html_attr(p["name"])}" />'
                   f"</figure>\n")
        out.append(f"Process id `{p['id']}`. [Open in the process viewer]({viewer}).\n")
        if p["doc"]:
            out.append(p["doc"] + "\n")
        checklist = p["file"].with_suffix(".checklist.md")
        if checklist.exists():
            out.append(f"Task checklist: [{checklist.name}]({REPO}processes/content/{checklist.name}).\n")
    return "\n".join(out) + "\n"


