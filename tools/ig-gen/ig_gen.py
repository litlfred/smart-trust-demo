"""Generate the IG's L2 content from the harness sources (standard library only).

The harness sources stay the single source of truth:
- processes/content/*.bpmn       -> input/business-processes/*.bpmn (copies)
                                    and input/pagecontent/business-processes.md,
                                    which shows the site's drawing of each
                                    (assets/img/workflows/*.svg, written by the
                                    harness's render:bpmn at publish)
- scenarios/roles.json           -> input/fsh/actors/*.fsh (one ActorDefinition
                                    per role, whose description shows the
                                    avatar of each actor that plays it and
                                    links what the role is implicated in:
                                    user-scenario steps, user stories, lanes
                                    and tasks, decision tables and gateways,
                                    data sets, indicators) and the personas
                                    and system actors pages
- scenarios/actors/*.json        -> the personas page (the fictional people
                                    and systems that play each role)
- scenarios/user-scenarios/*.json -> the "User scenarios" section of
                                    docs/journeys.md (between its markers)
- scenarios/stories.json, scenarios/story-requirements.json and that section
                                 -> input/pagecontent/scenarios.md
- docs/images/*                 -> data URIs in docs/index.md (data-img)
- docs/*.md and docs/*/*.md      -> input/pagecontent/<page>.md (DOC_PAGES),
                                    so the IG site carries the project pages
                                    and is the one site at the root
- dak/data-dictionary.json        -> input/fsh/dak/ (logical models, their
                                    mappings, the data-element and code-list
                                    CodeSystems and ValueSets) and
                                    input/pagecontent/dictionary.md
- processes/content/decisions/*.dmn -> input/fsh/dak/ (one PlanDefinition per
                                    decision table) and
                                    input/pagecontent/decision-logic.md
- dak/indicators.json             -> input/fsh/dak/ (one Measure per
                                    indicator) and input/pagecontent/indicators.md
  (all three read by tools/dak/dak.py)

Run:   python3 tools/ig-gen/ig_gen.py          (write)
       python3 tools/ig-gen/ig_gen.py --check  (fail if a file is stale)
"""
