def gen_glossary(roles, procs):
    """glossary/architecture.glossary.json: a SKOS concept for every element the ArchiMate overlay draws.

    Drawn from the overlay's own sources, never from the model: the person
    roles (scenarios/roles.json), the system and external actors and the
    parts each system holds (scenarios/actors/, meta.parts), the journeys
    (each BPMN process's documentation), and each country's instance of every
    RA building block its parts play. Every term is a candidate: extracted,
    not curated (folio-assistant-core's glossary-terms skill).
    """
    terms = []

    def term(tid, label, definition, source, **kw):
        if tid in SHORT_LABEL:
            kw = {"altLabel": [SHORT_LABEL[tid]], **kw}
        terms.append({"id": tid, "prefLabel": label, **({"definition": definition} if definition else {}),
                      **kw, "source": source, "status": "candidate"})

    for r in roles:
        if "person" in r.get("actorKinds", []):
            term(f"role-{r['id']}", r["title"], r["description"], f"scenarios/roles.json#{r['id']}",
                 **({"altLabel": r["otherNames"]} if r.get("otherNames") else {}),
                 isDefinedBy=f"http://smart.who.int/trust-demo/ActorDefinition/{actor_instance(r)}")
    instances = {}
    for a in actors():
        if a["kind"] == "person":
            continue
        term(f"actor-{a['id']}", a["title"], a.get("description"), f"scenarios/actors/{a['id']}.json")
        for part in a.get("meta", {}).get("parts", []):
            country = a["meta"]["country"]
            iid = instance_term(country, part["raBlock"])
            instances.setdefault(iid, (country, part["raBlock"]))
            term(f"part-{part['id']}", part["title"], part["description"], f"scenarios/actors/{a['id']}.json#{part['id']}",
                 broader=[f"actor-{a['id']}"], related=[iid])
    for p in procs:
        if p["code"]:
            term("journey-" + p["code"].lower().replace(".", "-"), p["name"], p.get("doc"), str(p["file"].relative_to(ROOT)) + f"#{p['id']}")
    for iid, (country, ra) in sorted(instances.items()):
        term(iid, f"{ra} ({country})",
             f"{country}'s instance of the DPI-H Reference Architecture building block {ra}: what {country}'s parts that play that block "
             f"are, one per jurisdiction, since neither country's systems are the other's.",
             "scenarios/actors/ (meta.country and meta.parts[].raBlock)")
    unknown = set(SHORT_LABEL) - {t["id"] for t in terms}
    if unknown:
        sys.exit(f"ig-gen: SHORT_LABEL names no term: {', '.join(sorted(unknown))}")
    doc = {"$schema": "folio-glossary/v1", "id": "architecture",
           "title": "SMART Trust demonstrator architecture",
           "description": "The people, systems, parts, journeys and per-country building blocks the demonstrator's ArchiMate overlay on the DPI-H RA draws, one concept each; each model element names its concept by skosConcept. Generated by tools/ig-gen/ig_gen.py.",
           "source": "scenarios/roles.json, scenarios/actors/, processes/content/",
           "terms": terms}
    return json.dumps(doc, indent=2, ensure_ascii=False) + "\n"


def build():
    roles = load("scenarios/roles.json")["roles"]
    by_role = {}
    for a in actors():
        for r in a.get("roles", []):
            by_role.setdefault(r, []).append(a)
    procs = processes()
    files = gen_actor_fsh(roles, by_role)
    files["input/pagecontent/personas.md"] = gen_personas(roles, by_role)
    files["input/pagecontent/system-actors.md"] = gen_system_actors(roles, by_role)
    files["input/pagecontent/business-processes.md"] = gen_processes(procs, roles)
    files["docs/journeys.md"] = gen_journeys()
    files["input/pagecontent/scenarios.md"] = gen_scenarios(roles, files["docs/journeys.md"])
    files["docs/index.md"] = inline_images("docs/index.md")
    for src, name in DOC_PAGES.items():
        files[f"input/pagecontent/{name}.md"] = doc_page(src, files.get(src))
    files.update(gen_dak(procs))
    files["glossary/architecture.glossary.json"] = gen_glossary(roles, procs)
    for rel in files:
        # Only the IG's pages: the docs/ sources keep bare requirement ids.
        if rel.endswith(".md") and rel.startswith("input/"):
            files[rel] = link_reqs(files[rel])
    for p in procs:
        files[f"input/business-processes/{p['file'].name}"] = p["file"].read_text()
    return files


def main():
    check = "--check" in sys.argv[1:]
    files = build()
    stale = []
    for rel, content in files.items():
        path = ROOT / rel
        if path.exists() and path.read_text() == content:
            continue
        stale.append(rel)
        if not check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    # Generated files whose source is gone.
    for d, pat in (("input/fsh/actors", "*.fsh"), ("input/business-processes", "*.bpmn"), ("input/fsh/dak", "*.fsh")):
        for p in (ROOT / d).glob(pat):
            rel = str(p.relative_to(ROOT))
            if rel not in files:
                stale.append(rel + " (orphan)")
                if not check:
                    p.unlink()
    if check and stale:
        for s in stale:
            print(f"ig-gen: stale: {s}", file=sys.stderr)
        print("ig-gen: run python3 tools/ig-gen/ig_gen.py and commit", file=sys.stderr)
        return 1
    print(f"ig-gen: {len(files)} file(s), {len(stale)} {'stale' if check else 'written'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
