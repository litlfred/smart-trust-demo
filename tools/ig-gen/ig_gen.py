def _feel(text, md=True):
    """A FEEL entry for reading: '-' as any, null as a dash, string literals
    unquoted (a code in a code span, a sentence as it is), one-of as a list."""
    if text == "-":
        return "any"
    if text == "null":
        return "\u2014"
    vals = [q if q or not o else o.strip() for q, o in re.findall(r'"([^"]*)"|([^,\s][^,]*)', text)]
    if md:
        vals = [v if " " in v else f"`{v}`" for v in vals]
    return vals[0] if len(vals) == 1 else "one of " + ", ".join(vals)


