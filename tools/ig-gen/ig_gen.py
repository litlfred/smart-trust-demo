#!/usr/bin/env python3
"""Generate the IG's L2 content from the harness sources (standard library only).

The harness sources stay the single source of truth:
- processes/content/*.bpmn       -> input/business-processes/*.bpmn (copies)
                                    and input/pagecontent/business-processes.md,
                                    which embeds processes/content/*.svg (drawn
                                    by tools/render-bpmn/render_bpmn.ts)
- scenarios/roles.json           -> input/fsh/actors/*.fsh (one ActorDefinition
                                    per role) and the personas and system
                                    actors pages
- scenarios/actors/*.json        -> the personas page (the fictional people
                                    and systems that play each role)
- scenarios/stories.json and the "User scenarios" section of
  docs/journeys.md               -> input/pagecontent/scenarios.md
- docs/images/*.svg              -> data URIs in docs/index.md (data-svg)
- docs/*.md and docs/*/*.md      -> input/pagecontent/<page>.md (DOC_PAGES),
                                    so the IG site carries the project pages
                                    and is the one site at the root

Run:   python3 tools/ig-gen/ig_gen.py          (write)
       python3 tools/ig-gen/ig_gen.py --check  (fail if a file is stale)
"""
import base64
import json
import pathlib
import re
import sys
import xml.etree.ElementTree as ET

ROOT = pathlib.Path(__file__).resolve().parents[2]
BPMN = "{http://www.omg.org/spec/BPMN/20100524/MODEL}"
HEADER = "<!-- Generated by tools/ig-gen/ig_gen.py from {src}. Do not edit; edit the source and rerun. -->\n\n"
FSH_HEADER = "// Generated by tools/ig-gen/ig_gen.py from {src}. Do not edit; edit the source and rerun.\n"
KIND_TYPE = {"person": "person", "system": "system", "external": "system"}
REPO = "https://github.com/litlfred/smart-trust-demo/blob/main/"
SITE = "https://litlfred.github.io/smart-trust-demo/"
# Each requirement id (STT-VER-006) links to its entry on smart-trust-tools'
# requirements page, which gives every requirement an anchor (stt-ver-006).
REQS = "https://litlfred.github.io/smart-trust-tools/viewers/requirements.html#"
REQ_ID = re.compile(r"STT-([A-Z0-9]{2,4})-(\d{3})(?:(\u2026|\.\.\.|\u2013)(\d{3}))?")
# Text that must not be rewritten: code, existing links, HTML tags, link targets.
NO_LINK = re.compile(r"`[^`\n]*`|\[[^\]\n]*\]\([^)\n]*\)|<[^>\n]*>|^\[[^\]\n]+\]:.*$", re.M)


def req_link(m):
    area, first, sep, last = m.groups()
    out = f"[STT-{area}-{first}]({REQS}stt-{area.lower()}-{first})"
    if last:
        out += f"{sep}[{last}]({REQS}stt-{area.lower()}-{last})"
    return out


def link_reqs(text):
    """Turn every bare requirement id in Markdown into a link, leaving code
    spans, links and HTML alone. A range (STT-PAY-001…005) links both ends."""
    out, at = [], 0
    for m in NO_LINK.finditer(text):
        out.append(REQ_ID.sub(req_link, text[at:m.start()]))
        out.append(m.group(0))
        at = m.end()
    out.append(REQ_ID.sub(req_link, text[at:]))
    return "".join(out)


def load(rel):
    return json.loads((ROOT / rel).read_text())


def pascal(s):
    return "".join(w[:1].upper() + w[1:] for w in re.split(r"[^A-Za-z0-9]+", s) if w)


def fsh_str(s):
    return s.replace("\\", "\\\\").replace('"', '\\"')


def html_attr(s):
    return (s or "").replace("&", "&amp;").replace('"', "&quot;").replace("<", "&lt;")


def anchor(title):
    """The id kramdown gives a heading: lower case, punctuation dropped,
    spaces to hyphens."""
    return re.sub(r"[^\w\- ]", "", title.lower()).strip().replace(" ", "-")


def cell(s):
    return (s or "").replace("|", "\\|").replace("\n", " ")


def actor_instance(role):
    return "TrustDemo.Role." + pascal(role["id"])


def actors():
    out = []
    for f in sorted((ROOT / "scenarios" / "actors").glob("*.json")):
        out.append(json.loads(f.read_text()))
    return out


def processes():
    out = []
    for f in sorted((ROOT / "processes" / "content").glob("*.bpmn")):
        root = ET.parse(f).getroot()
        proc = next(root.iter(BPMN + "process"))
        doc = proc.find(BPMN + "documentation")
        out.append({
            "file": f,
            "id": proc.get("id"),
            "name": proc.get("name"),
            "lanes": [l.get("id").removeprefix("Lane_") for l in root.iter(BPMN + "lane")],
            "doc": (doc.text or "").strip() if doc is not None else "",
        })
    return out


def gen_actor_fsh(roles, by_role):
    files = {}
    for r in roles:
        derived = []
        for a in by_role.get(r["id"], []):
            for url in a.get("meta", {}).get("definedBy", []):
                if url not in derived:
                    derived.append(url)
        desc = r["description"]
        if r.get("persona"):
            desc += "\n\n**Persona**: " + r["persona"]
        if r.get("otherNames"):
            desc += "\n\n**Also known as**: " + "; ".join(r["otherNames"])
        played = [a["title"] for a in by_role.get(r["id"], [])]
        if played:
            desc += "\n\n**Played in the journeys by**: " + "; ".join(played) + " (fictional)."
        lines = [
            FSH_HEADER.format(src="scenarios/roles.json"),
            f"Instance: {actor_instance(r)}",
            "InstanceOf: ActorDefinition",
            "Usage: #definition",
            f'* name = "{pascal(r["id"])}"',
            f'* title = "{fsh_str(r["title"])}"',
            "* status = #draft",
            "* experimental = true",
            f"* type = #{KIND_TYPE[r['actorKinds'][0]]}",
            f'* description = """\n{desc}\n"""',
            f'* documentation = "{REPO}scenarios/roles.json"',
        ]
        for url in derived:
            lines.append(f'* derivedFrom[+] = "{url}"')
        files[f"input/fsh/actors/{actor_instance(r)}.fsh"] = "\n".join(lines) + "\n"
    return files


def gen_personas(roles, by_role):
    out = [HEADER.format(src="scenarios/roles.json and scenarios/actors/*.json")]
    out.append("These are the generic personas of the journeys J1 to J4: the roles that play the lanes of the "
               "[business processes](business-processes.html), each defined as an `ActorDefinition`. "
               "The people and systems that play them in the journeys are fictional.\n")
    for kind, heading in (("person", "Generic personas"), ("system", "System actors"), ("external", "External actors")):
        rows = [r for r in roles if r["actorKinds"][0] == kind]
        if not rows:
            continue
        out.append(f"\n### {heading}\n")
        out.append("| Role | Description | Played by (fictional) | Also known as |\n|---|---|---|---|")
        for r in rows:
            link = f"[{cell(r['title'])}](ActorDefinition-{actor_instance(r)}.html)"
            played = "; ".join(a["title"] for a in by_role.get(r["id"], []))
            out.append(f"| {link} | {cell(r['description'])} | {cell(played)} | {cell('; '.join(r.get('otherNames', [])))} |")
        out.append("{: .grid }")
    others = [a for a in actors() if not a.get("roles")]
    if others:
        out.append("\n### Other people in the journeys\n")
        for a in others:
            out.append(f"- **{a['title']}**: {a['description']}")
    return "\n".join(out) + "\n"


def gen_system_actors(roles, by_role):
    out = [HEADER.format(src="scenarios/roles.json and scenarios/actors/*.json")]
    out.append("The system and external actors of the journeys, and the actor definitions of WHO SMART Trust, "
               "WHO smart-trust-phw and IHE ITI VHL each is derived from.\n")
    out.append("| Actor | Derived from |\n|---|---|")
    for r in roles:
        if r["actorKinds"][0] == "person":
            continue
        urls = []
        for a in by_role.get(r["id"], []):
            urls += [u for u in a.get("meta", {}).get("definedBy", []) if u not in urls]
        link = f"[{cell(r['title'])}](ActorDefinition-{actor_instance(r)}.html)"
        out.append(f"| {link} | {'<br/>'.join(f'<{u}>' for u in urls)} |")
    out.append("{: .grid }")
    return "\n".join(out) + "\n"


def gen_processes(procs, roles):
    titles = {r["id"]: r["title"] for r in roles}
    out = [HEADER.format(src="processes/content/*.bpmn")]
    out.append("One business process per journey. Each lane is a role on the [personas](personas.html) page; "
               "each task names the skill that performs it. The BPMN source of each process is in "
               "`processes/content/`, copied into the guide as `input/business-processes/`. "
               "Select a diagram to open it in the [process viewer](cat-harness/processes/), "
               "which lists each task and the skill that performs it.\n")
    out.append("| Process | Lanes | BPMN |\n|---|---|---|")
    for p in procs:
        lanes = ", ".join(titles.get(l, l) for l in p["lanes"])
        out.append(f"| [{cell(p['name'])}](#{anchor(p['name'])}) | {cell(lanes)} | [{p['file'].name}]({REPO}processes/content/{p['file'].name}) |")
    out.append("{: .grid }")
    for p in procs:
        stem = p["file"].stem
        viewer = f"cat-harness/processes/{stem}.html"
        out.append(f"\n### {p['name']}\n")
        # The SVG is drawn beside its source by tools/render-bpmn/render_bpmn.ts
        # and carried in the page as a data URI, so the page shows it whichever
        # route publishes the site (the IG's AST route copies no image files).
        svg = p["file"].with_suffix(".svg")
        if not svg.exists():
            sys.exit(f"ig-gen: {svg.relative_to(ROOT)} is missing: run bun tools/render-bpmn/render_bpmn.ts")
        data = base64.b64encode(svg.read_bytes()).decode("ascii")
        out.append(f'<figure class="bpmn-figure"><a href="{viewer}">'
                   f'<img src="data:image/svg+xml;base64,{data}" alt="BPMN diagram: {html_attr(p["name"])}" />'
                   f"</a></figure>\n")
        out.append(f"Process id `{p['id']}`. [Open in the process viewer]({viewer}).\n")
        if p["doc"]:
            out.append(p["doc"] + "\n")
        checklist = p["file"].with_suffix(".checklist.md")
        if checklist.exists():
            out.append(f"Task checklist: [{checklist.name}]({REPO}processes/content/{checklist.name}).\n")
    return "\n".join(out) + "\n"


def gen_scenarios(roles):
    titles = {r["id"]: r["title"] for r in roles}
    stories = load("scenarios/stories.json")["stories"]
    out = [HEADER.format(src="scenarios/stories.json and docs/journeys.md (User scenarios)")]
    out.append("### User stories\n")
    out.append("| Role | I want to | So that |\n|---|---|---|")
    for s in stories:
        role = s["role"]["role"]
        out.append(f"| {cell(titles.get(role, role))} | {cell(s['want'])} | {cell(s.get('soThat', ''))} |")
    out.append("{: .grid }\n")
    text = (ROOT / "docs" / "journeys.md").read_text()
    m = re.search(r"^## User scenarios\s*$(.*?)(?=^## |\Z)", text, re.S | re.M)
    if m:
        body = m.group(1).strip()
        body = re.sub(r"^### ", "#### ", body, flags=re.M)
        body = body.replace("](https://github.com/litlfred/smart-trust-demo/", "](https://github.com/litlfred/smart-trust-demo/")
        out.append("### User scenarios\n")
        out.append(body)
    return "\n".join(out) + "\n"


# The project's own pages, carried into the IG so its site is the one site.
# A page in a docs/ subdirectory becomes a flat IG page (the IG Publisher has
# no subdirectories); the old address forwards to it (FORWARDS).
DOC_PAGES = {
    "docs/index.md": "index",
    "docs/journeys.md": "journeys",
    "docs/vaxlink-examples.md": "vaxlink-examples",
    "docs/plan.md": "plan",
    "docs/dependencies.md": "dependencies",
    "docs/proposals/app-platform.md": "proposal-app-platform",
    "docs/upstream/who-smart-trust-phw-receive-a-vhl.md": "upstream-who-smart-trust-phw-receive-a-vhl",
}


def doc_page(src, text=None):
    """One docs page as an IG page: no front matter, no H1 (the IG gives the
    title), headings one level down, links to moved pages at their IG names."""
    text = text if text is not None else (ROOT / src).read_text()
    text = re.sub(r"\A---\n.*?\n---\n", "", text, flags=re.S)
    text = re.sub(r"\A\s*# [^\n]*\n", "", text)
    text = re.sub(r"^(#{2,5}) ", lambda m: "#" + m.group(1) + " ", text, flags=re.M)
    for other, name in DOC_PAGES.items():
        old = other[len("docs/"):-len(".md")] + ".html"
        text = re.sub(r"\]\((?:\.\./)?" + re.escape(old) + r"(#[^)]*)?\)", lambda m: f"]({name}.html{m.group(1) or ''})", text)
    return HEADER.format(src=src) + text.lstrip("\n")


def inline_svgs(src):
    """A docs page with each <img data-svg="images/x.svg" src="..."> carrying
    that SVG as a data URI, since neither the docs site nor the IG's AST route
    copies image files. docs/images/*.svg stay the editable source."""
    text = (ROOT / src).read_text()

    def inline(m):
        data = base64.b64encode((ROOT / "docs" / m.group(1)).read_bytes()).decode("ascii")
        return f'data-svg="{m.group(1)}" src="data:image/svg+xml;base64,{data}"'
    return re.sub(r'data-svg="(images/[\w.-]+\.svg)" src="[^"]*"', inline, text)


def build():
    roles = load("scenarios/roles.json")["roles"]
    by_role = {}
    for a in actors():
        for r in a.get("roles", []):
            by_role.setdefault(r, []).append(a)
    procs = processes()
    files = gen_actor_fsh(roles, by_role)
    files["input/pagecontent/personas.md"] = gen_personas(roles, by_role)
    files["input/pagecontent/system-actors.md"] = gen_system_actors(roles, by_role)
    files["input/pagecontent/business-processes.md"] = gen_processes(procs, roles)
    files["input/pagecontent/scenarios.md"] = gen_scenarios(roles)
    files["docs/index.md"] = inline_svgs("docs/index.md")
    for src, name in DOC_PAGES.items():
        files[f"input/pagecontent/{name}.md"] = doc_page(src, files.get(src))
    for rel in files:
        if rel.endswith(".md"):
            files[rel] = link_reqs(files[rel])
    for p in procs:
        files[f"input/business-processes/{p['file'].name}"] = p["file"].read_text()
    return files


def main():
    check = "--check" in sys.argv[1:]
    files = build()
    stale = []
    for rel, content in files.items():
        path = ROOT / rel
        if path.exists() and path.read_text() == content:
            continue
        stale.append(rel)
        if not check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    # Generated files whose source is gone.
    for d, pat in (("input/fsh/actors", "*.fsh"), ("input/business-processes", "*.bpmn")):
        for p in (ROOT / d).glob(pat):
            rel = str(p.relative_to(ROOT))
            if rel not in files:
                stale.append(rel + " (orphan)")
                if not check:
                    p.unlink()
    if check and stale:
        for s in stale:
            print(f"ig-gen: stale: {s}", file=sys.stderr)
        print("ig-gen: run python3 tools/ig-gen/ig_gen.py and commit", file=sys.stderr)
        return 1
    print(f"ig-gen: {len(files)} file(s), {len(stale)} {'stale' if check else 'written'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
