def pascal(s):
    return "".join(w[:1].upper() + w[1:] for w in re.split(r"[^A-Za-z0-9]+", s) if w)


def fsh_str(s):
    return s.replace("\\", "\\\\").replace('"', '\\"')


def html_attr(s):
    return (s or "").replace("&", "&amp;").replace('"', "&quot;").replace("<", "&lt;")


def anchor(title):
    """The id kramdown gives a heading: lower case, punctuation dropped,
    spaces to hyphens."""
    return re.sub(r"[^\w\- ]", "", title.lower()).strip().replace(" ", "-")


def cell(s):
    return (s or "").replace("|", "\\|").replace("\n", " ")


def actor_instance(role):
    return "TrustDemo.Role." + pascal(role["id"])


